"""Texts Home Assistant cannot translate for us: notifications and the
generated dashboard.

Entity names, select options and config forms are translated by Home
Assistant from translations/<lang>.json. The rest is rendered by this
integration in the language of Home Assistant, from texts/<lang>.json, with
English as the fallback. All of these files are generated by
scripts/build_translations.py: edit the tables there.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

LANGUAGES = ("en", "it")
DEFAULT_LANGUAGE = "en"
TEXTS_DIR = Path(__file__).parent / "texts"


def language(hass_language: str | None) -> str:
    """Supported language for a Home Assistant language tag (``it``, ``en-GB``)."""
    base = (hass_language or "").split("-")[0].lower()
    return base if base in LANGUAGES else DEFAULT_LANGUAGE


def load(lang: str) -> dict[str, Any]:
    """Texts of ``lang`` (blocking: file I/O)."""
    return json.loads((TEXTS_DIR / f"{lang}.json").read_text(encoding="utf-8"))


class Texts:
    """Texts of one language, looked up by dotted path."""

    def __init__(self, lang: str, data: dict[str, Any]) -> None:
        self.lang = lang
        self.data = data

    def __call__(self, path: str, **placeholders: Any) -> str:
        node: Any = self.data
        for part in path.split("."):
            node = node[part]
        return str(node).format(**placeholders) if placeholders else str(node)
